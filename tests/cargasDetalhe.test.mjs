import assert from 'node:assert/strict';
globalThis.HTMLElement = class {};
globalThis.customElements = { define() {} };
const { renderizarDetalhe, selo, data } = await import('../public/js/components/cargas/DetalheCarga.js');
const { filtrarHistorico, paginarHistorico, HistoricoCargas } = await import('../public/js/components/cargas/HistoricoCargas.js');
const erro = '<img src=x onerror=alert(1)>\n' + 'erro longo '.repeat(300);
const html = renderizarDetalhe({ id: 12, tipo: 'PARCIAL', status: 'FALHA', parametros: { anos: [2024, 2025], simbolos: ['<script>'], forcar: false }, mensagemErro: erro, etapas: [{ etapa: 'DFP', ordem: 2, status: 'FALHA', metricas: { gravados: 0, rejeitados: null, rejeitadosPorMotivo: { '<motivo>': 1 } }, erros: [erro], alertas: ['<alerta>'] }, { etapa: 'COTAHIST', ordem: 1, status: 'SUCESSO', metricas: { lidos: 20 } }], arquivos: [{ fonte: 'CVM', arquivo: '<arquivo>', etag: '"etag"', linhasCarregadas: null, status: 'SUCESSO' }] });
assert.ok(!html.includes('<img'));
assert.ok(!html.includes('<script>'));
assert.ok(html.includes('&lt;arquivo&gt;'));
assert.ok(html.includes('&lt;alerta&gt;'));
assert.ok(html.includes('erro longo '.repeat(300)));
assert.match(html, /Copiar erros completos/);
assert.match(html, /<td>—<\/td>/);
assert.match(html, />0<\/pre>/);
assert.ok(html.indexOf('COTAHIST') < html.indexOf('DFP'));
assert.match(selo('FALHA'), /✖ Falha/);
assert.match(selo('EXECUTANDO'), /Em execução/);
assert.equal(data('2026-10-18T02:00:00'), '17-10-2026 23:00');
assert.equal(data('2026-10-18T02:00:00Z'), '17-10-2026 23:00');
assert.equal(data('2026-10-18'), '18-10-2026');
assert.match(renderizarDetalhe(null), /Selecione/);
const lista = Array.from({ length: 25 }, (_, i) => ({ id: i + 1, criadaEm: `2026-10-${String(i + 1).padStart(2, '0')}`, status: i % 2 ? 'FALHA' : 'SUCESSO' }));
assert.deepEqual(filtrarHistorico(lista, { status: 'FALHA', inicio: '2026-10-03', fim: '2026-10-08' }).map(e => e.id), [8, 6, 4]);
const pagina = paginarHistorico(filtrarHistorico(lista), 3);
assert.equal(pagina.itens.length, 5);
assert.equal(pagina.paginas, 3);
assert.equal(paginarHistorico([], 99).pagina, 1);
const componente = new HistoricoCargas();
assert.match(componente.template(), /Nenhuma carga registrada ainda/);
componente._lista = [{ id: '"><img>', status: 'FALHA' }];
assert.ok(!componente.template().includes('<img>'));
componente._erro = '<erro>';
assert.match(componente.template(), /&lt;erro&gt;/);
console.log('cargasDetalhe.test.mjs ok');
